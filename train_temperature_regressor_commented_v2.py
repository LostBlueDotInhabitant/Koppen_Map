"""Heavily commented training & inference script for local temperature regression.

Updated for the new `kernelize.py` with `configure_kernel()` and the 12 water/ice
directional proximity vectors.

Feature layout generated by `kernelize.py` when `kernel_size=11` and
`include_water_vectors=True`:
  - Columns 0..483   (484 cols): Flattened 11x11x4 map kernel
                                 [altitude, ice_thickness, land_area_fraction, ice_area_fraction]
  - Columns 484..495  (12 cols): Directional proximity vectors:
                                 [4 all-water (unit E/N, inv-dist E/N),
                                  4 ice-free-water (unit E/N, inv-dist E/N),
                                  4 ice (unit E/N, inv-dist E/N)]
  - Columns 496..497   (2 cols): Global year-level forcings:
                                 [global_mean_temperature, co2_ppm]
  Total = 498 features per pixel-year sample.
"""

# `joblib` serializes the trained scikit-learn model and its metadata dictionary
# cleanly to disk so you can reload it later without retraining.
import joblib

# `numpy` is available for array inspection (e.g., min/max temperature summaries).
import numpy as np

# `HistGradientBoostingRegressor` is a histogram-based gradient boosted decision
# tree regressor. It handles ~498 features and hundreds of thousands of rows
# rapidly without requiring manual feature scaling.
from sklearn.ensemble import HistGradientBoostingRegressor

# `mean_absolute_error` (MAE) gives average error in degrees Celsius.
# `root_mean_squared_error` (RMSE) penalizes large outlier errors more heavily.
from sklearn.metrics import mean_absolute_error, root_mean_squared_error

# Import your updated `kernelize.py` helper module.
import kernelize as kz


# ===========================================================================
# 1. CONFIGURATION CONSTANTS
# ===========================================================================

# Raw GitHub URL prefix pointing to the folder containing:
#   - MapVariables.csv
#   - co2_temperature_historical_1900_2026.csv
#   - co2_temperature_projections_2026_2100.csv
GITHUB_BASE_URL = "https://raw.githubusercontent.com/<user>/<repo>/<branch>/<folder>/"

# Local directory path on your computer containing the two large temperature CSVs:
#   - tas_annual_mean_1deg_wide_celsius.csv
#   - temp_annual_all_scenarios_2015_2099.csv
TEMPERATURE_DIR = "C:/path/to/your/temperature/csvs"

# Folder where `kernelize.py` caches downloaded GitHub CSVs after first download.
CACHE_DIR = "data_cache"

# --- Kernel & Water-Vector Hyperparameters (passed to `kz.configure_kernel`) ---

# Width/height of the neighbourhood patch around each target pixel (must be odd).
# 11 -> 11x11 window centered on the target pixel.
KERNEL_SIZE = 11

# Neighbourhood window size used specifically to compute the water/ice vectors.
# - `None` means "use the same window size as `KERNEL_SIZE` (11x11)".
# - You can set a larger odd integer (e.g., `21` or `31`) so the proximity vectors
#   detect coastlines or ice sheets further away than the 11x11 kernel sees.
WATER_VECTOR_KERNEL_SIZE = None

# Whether to append the 12 directional water/ice vector columns (4 all-water,
# 4 open/ice-free water, 4 ice) after the flattened kernel columns.
INCLUDE_WATER_VECTORS = True

# Exponent `p` in `1 / distance**p` for the ice proximity vector (default = 1).
INVERSE_DISTANCE_POWER = 1

# Exponent `p` in `1 / distance**p` for the two water proximity vectors
# (all-water and ice-free water). Default = 2 (inverse-square weighting).
WATER_INVERSE_DISTANCE_POWER = 2

# Whether to shrink east-west grid offsets by `cos(latitude)` when computing
# distances for the proximity vectors:
# - `False`: distances are measured in raw 1-degree grid-pixel steps.
# - `True`: east-west pixel offsets shrink near the poles to approximate true
#   physical distance on a sphere.
SCALE_EW_BY_COS_LAT = False

# --- Dataset & Training Settings ---

# Shared Socioeconomic Pathway (SSP) scenario for 2015-2099 projections.
# Options: "ssp119", "ssp126", "ssp245", "ssp370", "ssp434", "ssp460", "ssp585".
SCENARIO = "ssp245"

# Split chronologically by year to prevent spatial-temporal data leakage:
# Neighboring pixels within the same year share overlapping 11x11 kernels and
# nearly identical temperatures. Holding out 2060-2099 tests true generalization
# to warmer future climate states.
TRAIN_YEARS = list(range(1900, 2060))  # 160 years (1900..2059)
VAL_YEARS = list(range(2060, 2100))    # 40 years  (2060..2099)

# Number of random pixels sampled per year out of the 64,800 global pixels.
# 5,000 pixels/year * 160 years = 800,000 training samples (~1.6 GB in float32).
# Set to `None` to use all 64,800 pixels per year if RAM permits (~20+ GB).
PIXELS_PER_YEAR = 5000

# Destination filename for the saved model artifact.
MODEL_OUTPUT_PATH = "temp_regressor_11x11.joblib"


# ===========================================================================
# 2. MODULE CONFIGURATION & DATASET CONSTRUCTION
# ===========================================================================

def configure_pipeline():
    """Initialize data paths and kernel/water-vector settings in `kernelize.py`."""

    # Tell `kernelize.py` where to fetch GitHub files and local temperature CSVs.
    kz.configure_data_sources(
        github_base_url=GITHUB_BASE_URL,
        temperature_directory=TEMPERATURE_DIR,
        cache_directory=CACHE_DIR,
    )

    # Set global kernel defaults inside `kernelize._KERNEL_SETTINGS`.
    # Note: In `kernelize.py`, `configure_kernel()` overwrites ALL six settings
    # every time it is called, so we pass every setting explicitly here.
    kz.configure_kernel(
        kernel_size=KERNEL_SIZE,
        water_vector_kernel_size=WATER_VECTOR_KERNEL_SIZE,
        include_water_vectors=INCLUDE_WATER_VECTORS,
        inverse_distance_power=INVERSE_DISTANCE_POWER,
        water_inverse_distance_power=WATER_INVERSE_DISTANCE_POWER,
        scale_east_west_by_cos_latitude=SCALE_EW_BY_COS_LAT,
    )


def build_datasets():
    """Build training (X_train, y_train) and validation (X_val, y_val) arrays."""

    # Apply data source paths and kernel settings before loading any data.
    configure_pipeline()

    # IMPORTANT: Notice `kernel_size=None` below!
    # In the updated `kernelize.py`, passing `kernel_size=None` tells the function
    # to read `kernel_size` (11) from `configure_kernel()` instead of overriding it
    # with a positional integer (like `5` in the quick example).
    print("Building training dataset...")
    X_train, y_train = kz.make_temperature_regression_training_data_from_files(
        kernel_size=None,
        scenario=SCENARIO,
        years=TRAIN_YEARS,
        pixels_per_year=PIXELS_PER_YEAR,
        global_temperature_from="file",
    )

    # Build the validation set on the held-out future years (2060-2099) using
    # the exact same configured kernel and water-vector parameters.
    print("Building validation dataset...")
    X_val, y_val = kz.make_temperature_regression_training_data_from_files(
        kernel_size=None,
        scenario=SCENARIO,
        years=VAL_YEARS,
        pixels_per_year=PIXELS_PER_YEAR,
        global_temperature_from="file",
    )

    # Verify array dimensions:
    # With KERNEL_SIZE=11 and INCLUDE_WATER_VECTORS=True:
    #   484 (kernel) + 12 (water/ice vectors) + 2 (global temp, CO2) = 498 columns.
    print(f"X_train shape: {X_train.shape}, y_train shape: {y_train.shape}")
    print(f"X_val shape:   {X_val.shape}, y_val shape:   {y_val.shape}")

    return X_train, y_train, X_val, y_val


# ===========================================================================
# 3. MODEL TRAINING & EVALUATION
# ===========================================================================

def train_and_evaluate(X_train, y_train, X_val, y_val):
    """Train HistGradientBoostingRegressor and evaluate MAE / RMSE on validation years."""

    model = HistGradientBoostingRegressor(
        # Squared error loss targets the conditional mean local temperature.
        loss="squared_error",

        # Shrinkage factor per boosting step; 0.05 balances accuracy and speed.
        learning_rate=0.05,

        # Upper bound on number of trees; early stopping will halt sooner if
        # validation loss stops improving.
        max_iter=400,

        # Maximum leaves per tree (63 allows multi-way interactions between
        # kernel cells, water proximity vectors, and global CO2/temperature).
        max_leaf_nodes=63,

        # Minimum samples per leaf to avoid overfitting isolated grid cells.
        min_samples_leaf=50,

        # L2 regularization on leaf values for smoother generalization.
        l2_regularization=1.0,

        # Hold out 10% of `X_train` internally to monitor progress and stop
        # early once validation loss plateaus.
        early_stopping=True,
        validation_fraction=0.1,

        # Random seed for reproducible binning and internal validation split.
        random_state=42,
    )

    # Fit the model. Tree ensembles do not require feature normalization, so raw
    # meters (altitude), percentages (land/ice fraction), vector sums, and ppm (CO2)
    # can be passed directly as produced by `kernelize.py`.
    print("Training HistGradientBoostingRegressor...")
    model.fit(X_train, y_train)
    print(f"Training completed in {model.n_iter_} boosting iterations.")

    # Predict local annual mean temperatures (in C) for the held-out years.
    val_preds = model.predict(X_val)

    # Calculate average absolute error (MAE) and root mean squared error (RMSE).
    mae = mean_absolute_error(y_val, val_preds)
    rmse = root_mean_squared_error(y_val, val_preds)

    print(f"Validation MAE:  {mae:.4f} C")
    print(f"Validation RMSE: {rmse:.4f} C")

    return model


# ===========================================================================
# 4. FULL-GLOBE INFERENCE FOR A TARGET YEAR
# ===========================================================================

def predict_global_grid_for_year(model, target_year, scenario=SCENARIO, epoch="0ka"):
    """Predict a complete (180, 360) global temperature map for `target_year`."""

    # Load global mean temperature and CO2 concentration dicts up to `target_year`.
    global_temp_by_year, co2_by_year = kz.load_global_mean_temperature_and_co2_by_year(
        scenario=scenario,
        last_year=target_year,
    )

    # Build the feature matrix for all 64,800 pixels on the globe:
    # Passing `kernel_size=None` ensures `make_temperature_regression_features`
    # uses the exact `configure_kernel()` settings (11x11 kernel + 12 water/ice
    # vector columns + 2 global columns = 498 columns).
    X_grid = kz.make_temperature_regression_features(
        kernel_size=None,
        global_mean_temperature=global_temp_by_year[target_year],
        co2_ppm=co2_by_year[target_year],
        epoch=epoch,
    )

    # Predict temperature for every pixel -> 1D array of shape (64800,).
    flat_preds = model.predict(X_grid)

    # Reshape back into `kernelize.py`'s standard (180, 360) lat/lon grid.
    return kz.reshape_predictions_to_grid(flat_preds)


# ===========================================================================
# 5. MAIN ENTRY POINT
# ===========================================================================

def main():
    """Run data preparation, model training, evaluation, saving, and sample inference."""

    # Step 1: Configure `kernelize.py` and build train/validation arrays.
    X_train, y_train, X_val, y_val = build_datasets()

    # Step 2: Fit the regressor and report validation MAE and RMSE.
    model = train_and_evaluate(X_train, y_train, X_val, y_val)

    # Step 3: Save both the trained model and the exact `configure_kernel()`
    # parameters used to build its features, so future inference scripts can
    # call `kz.configure_kernel(**bundle["kernel_settings"])` to guarantee an
    # exact feature-column match.
    joblib.dump(
        {
            "model": model,
            "kernel_settings": {
                "kernel_size": KERNEL_SIZE,
                "water_vector_kernel_size": WATER_VECTOR_KERNEL_SIZE,
                "include_water_vectors": INCLUDE_WATER_VECTORS,
                "inverse_distance_power": INVERSE_DISTANCE_POWER,
                "water_inverse_distance_power": WATER_INVERSE_DISTANCE_POWER,
                "scale_east_west_by_cos_latitude": SCALE_EW_BY_COS_LAT,
            },
            "scenario": SCENARIO,
        },
        MODEL_OUTPUT_PATH,
    )
    print(f"Saved trained model bundle to: {MODEL_OUTPUT_PATH}")

    # Step 4: Predict and inspect a sample (180, 360) global grid for 2075.
    sample_year = 2075
    grid_2075 = predict_global_grid_for_year(model, target_year=sample_year)
    print(f"Predicted {sample_year} global grid shape: {grid_2075.shape}")
    print(
        f"Min/Max predicted temperature in {sample_year}: "
        f"{grid_2075.min():.2f} C / {grid_2075.max():.2f} C"
    )


if __name__ == "__main__":
    main()
